/** Assistant page: Gemini chat + structured daily-routine generation. */
import { useState } from 'react';
import { CalendarCheck, Loader2, ShieldCheck, Sparkles } from 'lucide-react';
import type { DailyRoutine } from '@vayusense/shared';
import { ChatPanel } from '../components/assistant/ChatPanel';
import { RoutineTimeline } from '../components/routine/RoutineTimeline';
import { Button, Card, SectionTitle } from '../components/ui';
import { useAirQuality } from '../hooks/useAirQuality';
import { api, type ApiMeta } from '../lib/api';
import { track } from '../lib/analytics';
import { useAppStore } from '../store/useAppStore';

export default function AssistantPage() {
  const persona = useAppStore((s) => s.persona);
  const city = useAppStore((s) => s.city);
  const coords = useAppStore((s) => s.coords);
  const { snapshot } = useAirQuality(coords, city);

  const [commuteKm, setCommuteKm] = useState(12);
  const [routine, setRoutine] = useState<DailyRoutine | null>(null);
  const [meta, setMeta] = useState<ApiMeta | null>(null);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const generate = async () => {
    setGenerating(true);
    setError(null);
    try {
      const result = await api.generateRoutine({
        persona,
        city,
        aqi: snapshot?.aqi ?? 415,
        householdSize: 4,
        commuteKm,
        sensitivities: [],
      });
      setRoutine(result);
      setMeta(result.meta);
      track('routine_generated', { persona, demo: result.meta.demo });
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Routine generation failed');
    } finally {
      setGenerating(false);
    }
  };

  return (
    <div className="space-y-6">
      <SectionTitle
        title="Your GenAI smog companion"
        subtitle="Gemini reasons over live air quality and your household profile to plan a safer, lower-emission day."
      />
      <div className="grid gap-4 lg:grid-cols-5">
        <div className="lg:col-span-3">
          <ChatPanel aqi={snapshot?.aqi} />
        </div>
        <div className="space-y-4 lg:col-span-2">
          <Card>
            <div className="flex items-center gap-2">
              <CalendarCheck className="h-4 w-4 text-teal-300" aria-hidden="true" />
              <h3 className="font-display text-base font-semibold text-white">
                Generate my smog-safe day
              </h3>
            </div>
            <p className="mt-2 text-sm text-mist-500">
              A chronological low-emission routine: exposure-aware timing, mode shifts and indoor
              air actions — validated against a strict JSON contract.
            </p>
            <label className="mt-3 block text-xs text-mist-500">
              Daily commute (km)
              <input
                type="number"
                min={0}
                max={200}
                value={commuteKm}
                onChange={(event) => setCommuteKm(Number(event.target.value) || 0)}
                className="input mt-1"
              />
            </label>
            <Button className="mt-3 w-full" onClick={() => void generate()} disabled={generating}>
              {generating ? (
                <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
              ) : (
                <Sparkles className="h-4 w-4" aria-hidden="true" />
              )}
              {generating ? 'Planning your day…' : 'Generate routine'}
            </Button>
            {error ? (
              <p role="alert" className="mt-2 text-sm text-red-300">
                {error}
              </p>
            ) : null}
            {meta ? (
              <p className="mt-2 text-xs text-mist-500">
                Generated by {meta.demo ? 'deterministic demo engine' : meta.model}
              </p>
            ) : null}
          </Card>

          <Card>
            <div className="flex items-center gap-2">
              <ShieldCheck className="h-4 w-4 text-teal-300" aria-hidden="true" />
              <h3 className="font-display text-base font-semibold text-white">Safety by design</h3>
            </div>
            <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-mist-500">
              <li>Gemini safety filters block harmful content categories.</li>
              <li>No diagnosis or prescriptions — emergencies escalate to care.</li>
              <li>Every response is Zod-validated before it reaches you.</li>
              <li>Prompt-injection resistant system instructions.</li>
            </ul>
          </Card>
        </div>
      </div>

      {routine ? <RoutineTimeline routine={routine} /> : null}
    </div>
  );
}
